// Course evaluation between guessed course and secret target course
function evaluateCourseGuess(guess, target) {
  const isWin = guess.id === target.id;

  // 1. Racetrack
  let trackStatus = "mismatch";
  if (guess.track_id === target.track_id) {
    trackStatus = "exact";
  } else if (guess.region === target.region) {
    trackStatus = "partial"; // Same geographic region (e.g. Hokkaido: Sapporo & Hakodate)
  }

  // 2. Distance Length in meters
  let distStatus = "mismatch";
  const distDiff = Math.abs(guess.length - target.length);
  if (distDiff === 0) {
    distStatus = "exact";
  } else if (distDiff <= 200) {
    distStatus = "partial";
  }
  let distArrow = "";
  if (target.length > guess.length) distArrow = "⬆️";
  else if (target.length < guess.length) distArrow = "⬇️";

  // 3. Distance Type (Short, Mile, Medium, Long) - NO YELLOW
  let distTypeStatus = (guess.division === target.division) ? "exact" : "mismatch";

  // 4. Surface / Terrain (Turf vs Dirt)
  let terrainStatus = (guess.terrain === target.terrain) ? "exact" : "mismatch";

  // 5. Direction (Right, Left, Straight)
  let dirStatus = (guess.direction === target.direction) ? "exact" : "mismatch";

  // 6. Late Race Start Location (C2, C3, C4, Backstretch, Homestretch)
  // Yellow should just be corner vs straight:
  // Both are corners (e.g. C2, C3, C4) -> Yellow
  // Both are straights (Backstretch vs Homestretch) -> Yellow
  // One corner and one straight -> Gray (mismatch)
  let lateRaceStatus = "mismatch";
  const isCorner = loc => loc.startsWith("C");
  const isStraight = loc => ["Backstretch", "Homestretch"].includes(loc);

  if (guess.late_race === target.late_race) {
    lateRaceStatus = "exact";
  } else if (
    (isCorner(guess.late_race) && isCorner(target.late_race)) ||
    (isStraight(guess.late_race) && isStraight(target.late_race))
  ) {
    lateRaceStatus = "partial";
  }

  // 7. Corners count
  let cornersStatus = "mismatch";
  const cornersDiff = Math.abs(guess.corners - target.corners);
  if (cornersDiff === 0) {
    cornersStatus = "exact";
  } else if (cornersDiff <= 1) {
    cornersStatus = "partial";
  }
  let cornersArrow = "";
  if (target.corners > guess.corners) cornersArrow = "⬆️";
  else if (target.corners < guess.corners) cornersArrow = "⬇️";

  // 8. Final Straight length
  let straightStatus = "mismatch";
  const straightDiff = Math.abs(guess.final_straight - target.final_straight);
  if (straightDiff === 0) {
    straightStatus = "exact";
  } else if (straightDiff <= 35) {
    straightStatus = "partial";
  }
  let straightArrow = "";
  if (target.final_straight > guess.final_straight) straightArrow = "⬆️";
  else if (target.final_straight < guess.final_straight) straightArrow = "⬇️";

  return {
    isWin,
    guess,
    target,
    results: {
      track: { val: guess.track_name, status: trackStatus },
      distance: { val: `${guess.length}m`, arrow: distArrow, status: distStatus, diff: target.length - guess.length },
      distance_type: { val: guess.division, status: distTypeStatus },
      terrain: { val: guess.terrain, status: terrainStatus },
      direction: { val: guess.direction, status: dirStatus },
      late_race: { val: guess.late_race, status: lateRaceStatus },
      corners: { val: guess.corners, arrow: cornersArrow, status: cornersStatus, diff: target.corners - guess.corners },
      straight: { val: `${guess.final_straight}m`, arrow: straightArrow, status: straightStatus, diff: target.final_straight - guess.final_straight }
    }
  };
}

// Daily course deterministic selector (FNV-1a + Murmur3 bit-mixer)
function getDailyCourse(dateString) {
  if (!dateString) dateString = new Date().toISOString().slice(0, 10);
  let h = 0x811c9dc5 ^ 0x19283746;
  for (let i = 0; i < dateString.length; i++) {
    h ^= dateString.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  const index = (h >>> 0) % ALL_COURSES.length;
  return ALL_COURSES[index];
}

